import { readFileSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { CONCEPT_MAP_VIEW, CONCEPT_PROVINCE_PATHS } from '@/lib/jelajah/concept/indonesia-paths';
import { parseProvinceGeo } from '@/lib/jelajah/geo';
import { KNOWN_PROVINCES } from '@/lib/jelajah/provinces';

const root = fileURLToPath(new URL('../../', import.meta.url));
const GENERATED = `${root}lib/jelajah/concept/indonesia-paths.ts`;

describe('concept video map outline (Phase 19)', () => {
  it('stays within the 60 KB raw budget', () => {
    expect(statSync(GENERATED).size).toBeLessThan(60 * 1024);
  });

  it('is generated (header) and has a matching package script', () => {
    expect(readFileSync(GENERATED, 'utf8')).toContain('GENERATED by scripts/build-concept-map.mjs');
    const pkg = JSON.parse(readFileSync(`${root}package.json`, 'utf8')) as { scripts: Record<string, string> };
    expect(pkg.scripts['concept:map']).toContain('scripts/build-concept-map.mjs');
  });

  it('has every province that the hub map draws, each once, with a known code', () => {
    const geo = JSON.parse(readFileSync(`${root}public/jelajah/geo/indonesia-provinces.json`, 'utf8'));
    const hub = parseProvinceGeo(geo, KNOWN_PROVINCES);
    const hubCodes = hub.shapes.map((s) => s.kode).filter((k): k is string => k !== null);
    const codes = CONCEPT_PROVINCE_PATHS.map((p) => p.kode);
    expect(new Set(codes).size).toBe(codes.length);
    expect([...codes].sort()).toEqual([...new Set(hubCodes)].sort());
    const known = new Set(KNOWN_PROVINCES.map((p) => p.kode));
    for (const c of codes) expect(known.has(c), c).toBe(true);
    // Only provinces without 2019 boundaries are missing (the hub lists them in its text view).
    const missing = KNOWN_PROVINCES.filter((p) => !codes.includes(p.kode)).map((p) => p.kode);
    expect(missing.sort()).toEqual(hub.provincesWithoutShape.map((p) => p.kode).sort());
    expect(codes).toContain('16'); // Sumatera Selatan, the dive target of scene 5
  });

  it('paths use only M/l/z with integers, centroids lie inside the view, sorted west to east', () => {
    for (const p of CONCEPT_PROVINCE_PATHS) {
      expect(p.d, p.kode).toMatch(/^(M\d+ \d+l[-\d ]+z)+$/);
      expect(p.cx).toBeGreaterThanOrEqual(0);
      expect(p.cx).toBeLessThanOrEqual(CONCEPT_MAP_VIEW.width);
      expect(p.cy).toBeGreaterThanOrEqual(0);
      expect(p.cy).toBeLessThanOrEqual(CONCEPT_MAP_VIEW.height);
    }
    const xs = CONCEPT_PROVINCE_PATHS.map((p) => p.cx);
    expect(xs).toEqual([...xs].sort((a, b) => a - b));
    // Aceh is the westernmost province, Papua the easternmost.
    expect(CONCEPT_PROVINCE_PATHS[0].kode).toBe('11');
    expect(['91', '93']).toContain(CONCEPT_PROVINCE_PATHS[CONCEPT_PROVINCE_PATHS.length - 1].kode);
  });
});
